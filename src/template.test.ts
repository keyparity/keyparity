import { expect, test } from "bun:test";
import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseTemplate } from "./sources.ts";
import { buildTemplate } from "./template.ts";

const app = join(import.meta.dir, "../test/fixtures/app");
const cli = (...args: string[]) => Bun.spawn(["bun", join(import.meta.dir, "index.ts"), ...args], { stdout: "pipe", stderr: "pipe" });

test("lists every name the code reads, sorted, with empty values", () => {
  expect(buildTemplate(["DB_URL", "API_KEY"])).toBe("# Generated by keyparity. Fill in values locally, and never commit them.\nAPI_KEY=\nDB_URL=\n");
});

test("the output parses back to the same names", () => {
  expect(parseTemplate(buildTemplate(["B", "A"]))).toEqual(["A", "B"]);
});

test("CLI prints the template for a folder, from code references only", async () => {
  const proc = cli("generate-template", "--path", app);
  const out = await new Response(proc.stdout).text();
  expect(await proc.exited).toBe(0);
  expect(parseTemplate(out)).toEqual(["API_KEY", "DB_URL"]); // DEPLOY_TOKEN is a CI secret, not a local var
});

test("CLI --write creates .env.example, and refuses to overwrite one", async () => {
  const root = await mkdtemp(join(tmpdir(), "keyparity-"));
  await writeFile(join(root, "a.ts"), "process.env.PORT");
  const first = cli("generate-template", "--path", root, "--write");
  expect(await first.exited).toBe(0);
  expect(await Bun.file(join(root, ".env.example")).text()).toContain("PORT=");
  const second = cli("generate-template", "--path", root, "--write");
  expect(await second.exited).toBe(1);
  expect(await new Response(second.stderr).text()).toContain("already exists");
});
